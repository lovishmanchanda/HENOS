//! System clipboard access for HENOS on Windows, macOS and Linux.
//!
//! Two pieces, matching what `henos_core::clipboard` needs from a platform:
//!
//! - [`SystemClipboard`] puts received content on the system clipboard.
//! - [`watch`] reports what the user copies.
//!
//! Content that an app marks as secret, as password managers do, is never
//! reported. See [`is_concealed`].

use std::{
    sync::{mpsc, Mutex},
    thread::{self, JoinHandle},
};

use clipboard_rs::{
    common::RustImage, Clipboard, ClipboardContext, ClipboardHandler, ClipboardWatcher,
    ClipboardWatcherContext, ContentFormat, RustImageData, WatcherShutdown,
};
use henos_core::{ClipboardBackend, ClipboardContent, PngImage};
use tracing::debug;

/// Clipboard format names that apps use to say "do not record or share this".
///
/// macOS has a convention (nspasteboard.org) followed by password managers;
/// Windows has formats that keep an item out of clipboard history and cloud
/// sync.
const CONCEALED_FORMATS: &[&str] = &[
    // macOS
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    // Windows
    "ExcludeClipboardContentFromMonitorProcessing",
    "CanIncludeInClipboardHistory",
    "CanUploadToCloudClipboard",
    // Linux (KDE)
    "x-kde-passwordManagerHint",
];

/// Whether the clipboard's current content is marked as secret, judging by
/// the formats present on it.
pub fn is_concealed<S: AsRef<str>>(formats: &[S]) -> bool {
    formats.iter().any(|format| {
        CONCEALED_FORMATS
            .iter()
            .any(|concealed| format.as_ref().eq_ignore_ascii_case(concealed))
    })
}

/// The system clipboard as a place to put received content.
pub struct SystemClipboard {
    context: Mutex<ClipboardContext>,
}

impl SystemClipboard {
    pub fn new() -> Result<Self, String> {
        let context = ClipboardContext::new().map_err(|e| e.to_string())?;
        Ok(Self {
            context: Mutex::new(context),
        })
    }
}

impl ClipboardBackend for SystemClipboard {
    fn write(&self, content: &ClipboardContent) -> Result<(), String> {
        let context = self.context.lock().unwrap();
        match content {
            ClipboardContent::Text(text) => {
                context.set_text(text.clone()).map_err(|e| e.to_string())
            }
            ClipboardContent::Image(image) => {
                let picture = RustImageData::from_bytes(image.png()).map_err(|e| e.to_string())?;
                context.set_image(picture).map_err(|e| e.to_string())
            }
            _ => Err("this kind of clipboard content is not supported yet".into()),
        }
    }
}

/// A running clipboard watcher. Stops when dropped.
pub struct ClipboardWatch {
    shutdown: Option<WatcherShutdown>,
    thread: Option<JoinHandle<()>>,
}

impl Drop for ClipboardWatch {
    fn drop(&mut self) {
        if let Some(shutdown) = self.shutdown.take() {
            shutdown.stop();
        }
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

struct Handler<F> {
    context: ClipboardContext,
    on_copy: F,
}

impl<F: FnMut(ClipboardContent)> ClipboardHandler for Handler<F> {
    fn on_clipboard_change(&mut self) {
        match self.context.available_formats() {
            Ok(formats) if is_concealed(&formats) => {
                debug!("clipboard content is marked as secret, not sharing it");
                return;
            }
            Ok(_) => {}
            Err(e) => {
                // If we cannot tell whether it is secret, do not share it.
                debug!("could not inspect the clipboard, skipping this change: {e}");
                return;
            }
        }
        // Text wins when both are present: apps such as spreadsheets put a
        // picture of the cells next to the text, and the text is what is
        // meant.
        if let Ok(text) = self.context.get_text() {
            if !text.is_empty() {
                (self.on_copy)(ClipboardContent::Text(text));
                return;
            }
        }
        if !self.context.has(ContentFormat::Image) {
            // Files, or nothing we share.
            return;
        }
        let png = self
            .context
            .get_image()
            .and_then(|picture| picture.to_png())
            .map(|encoded| encoded.get_bytes().to_vec());
        match png
            .map_err(|e| e.to_string())
            .and_then(|bytes| PngImage::new(bytes).map_err(|e| e.to_string()))
        {
            Ok(image) => (self.on_copy)(ClipboardContent::Image(image)),
            Err(e) => debug!("copied image not shared: {e}"),
        }
    }
}

/// macOS has no clipboard-change event, so the watcher has to look at a
/// counter now and then. Once a second is cheap and still feels immediate by
/// the time someone has moved to their other device. Windows and Linux are
/// told about changes by the system and do not poll at all.
#[cfg(target_os = "macos")]
fn new_watcher<T: ClipboardHandler>() -> clipboard_rs::Result<ClipboardWatcherContext<T>> {
    ClipboardWatcherContext::new_with_interval(std::time::Duration::from_secs(1))
}

#[cfg(not(target_os = "macos"))]
fn new_watcher<T: ClipboardHandler>() -> clipboard_rs::Result<ClipboardWatcherContext<T>> {
    ClipboardWatcherContext::new()
}

/// Calls `on_copy` with the new content each time the system clipboard
/// changes, from a dedicated thread.
///
/// This fires for every change, including ones made through
/// [`SystemClipboard`]; `ClipboardSync::local_copy` recognises those and does
/// not send them back.
pub fn watch<F>(on_copy: F) -> Result<ClipboardWatch, String>
where
    F: FnMut(ClipboardContent) + Send + 'static,
{
    let (ready_tx, ready_rx) = mpsc::channel::<Result<WatcherShutdown, String>>();
    let thread = thread::Builder::new()
        .name("henos-clipboard-watch".into())
        .spawn(move || {
            let setup = ClipboardContext::new().and_then(|context| {
                let watcher = new_watcher()?;
                Ok((context, watcher))
            });
            let (context, mut watcher) = match setup {
                Ok(parts) => parts,
                Err(e) => {
                    let _ = ready_tx.send(Err(e.to_string()));
                    return;
                }
            };
            let shutdown = watcher
                .add_handler(Handler { context, on_copy })
                .get_shutdown_channel();
            let _ = ready_tx.send(Ok(shutdown));
            // Blocks until the shutdown channel is used.
            watcher.start_watch();
        })
        .map_err(|e| e.to_string())?;

    let shutdown = ready_rx
        .recv()
        .map_err(|_| "clipboard watcher stopped before it started".to_owned())??;
    Ok(ClipboardWatch {
        shutdown: Some(shutdown),
        thread: Some(thread),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    // These tests deliberately do not touch the real system clipboard.

    #[test]
    fn password_manager_content_is_recognised() {
        assert!(is_concealed(&[
            "public.utf8-plain-text",
            "org.nspasteboard.ConcealedType"
        ]));
        assert!(is_concealed(&[
            "CF_UNICODETEXT",
            "ExcludeClipboardContentFromMonitorProcessing"
        ]));
        assert!(is_concealed(&["x-kde-passwordManagerHint"]));
        // Case differences between platforms do not matter.
        assert!(is_concealed(&["org.nspasteboard.concealedtype"]));
    }

    #[test]
    fn ordinary_content_is_not_concealed() {
        assert!(!is_concealed(&["public.utf8-plain-text", "public.html"]));
        assert!(!is_concealed(&["CF_UNICODETEXT", "CF_TEXT", "CF_LOCALE"]));
        assert!(!is_concealed::<&str>(&[]));
    }
}
